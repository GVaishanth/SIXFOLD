const hit = (id: StatusId, duration: number, chance = 1, intensity = 1): StatusApplication => ({
  id,
  duration,
  chance,
  intensity,
});

type ElementSeed = Omit<ElementDef, 'color' | 'colorInt' | 'colorCore' | 'colorCoreInt' | 'gradient'>;

/**
 * The two stops of an element's palette decide its whole presentation: the
 * brighter stop is the identity colour used by UI, glyphs and projectile tints,
 * the deeper stop is the core used inside particles and screen washes. Panels
 * get the identity colour fading into the panel body, never a rainbow.
 */
const element = (seed: ElementSeed): ElementDef => {
  const palette = ELEMENT_PALETTE[seed.id];
  const bright = luminance(palette.edge) >= luminance(palette.core) ? palette.edge : palette.core;
  const deep = bright === palette.edge ? palette.core : palette.edge;
  return {
    ...seed,
    color: bright,
    colorInt: hexToInt(bright),
    colorCore: deep,
    colorCoreInt: hexToInt(deep),
    gradient: [bright, mixHex(deep, '#0A0F1A', 0.72)],
  };
};

