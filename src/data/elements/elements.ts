/** Canonical element order — starters, primordial branch, then discovery order. */
export const ALL_ELEMENTS: ElementDef[] = Object.values(ELEMENT_REGISTRY).sort((a, b) => a.index - b.index);

export const STARTER_ELEMENT_IDS: ElementId[] = ALL_ELEMENTS.filter(
  (def) => def.unlock.kind === 'starter',
).map((def) => def.id);

/** Boot-time integrity check: 25 elements, matching parents/children, unique ids. */
export function validateElementRegistry(): string[] {
  const problems: string[] = [];
  const ids = Object.keys(ELEMENT_REGISTRY) as ElementId[];
  if (ids.length !== 25) problems.push(`Element registry must contain exactly 25 elements (found ${ids.length})`);

  for (const def of ALL_ELEMENTS) {
    for (const parent of def.parents) {
      if (!ELEMENT_REGISTRY[parent]) problems.push(`${def.id} references missing parent ${parent}`);
      else if (!ELEMENT_REGISTRY[parent].children.includes(def.id)) {
        problems.push(`${parent} does not list ${def.id} as a child`);
      }
    }
    for (const child of def.children) {
      if (!ELEMENT_REGISTRY[child]) problems.push(`${def.id} references missing child ${child}`);
      else if (!ELEMENT_REGISTRY[child].parents.includes(def.id)) {
        problems.push(`${child} does not list ${def.id} as a parent`);
      }
    }
  }
  return problems;
}
