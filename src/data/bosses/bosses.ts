export const BOSS_LIST: BossDef[] = Object.values(BOSS_REGISTRY);

export function getBoss(id: string | null | undefined): BossDef | null {
  if (!id) return null;
  return BOSS_REGISTRY[id] ?? null;
}

export function getMajorBossForFloor(floor: number): BossDef | null {
  return BOSS_LIST.find((boss) => boss.rank === 'major' && boss.floor === floor) ?? null;
}

export function getMiniBossForFloor(floor: number): BossDef | null {
  return BOSS_LIST.find((boss) => boss.rank === 'miniboss' && boss.floor === floor) ?? null;
}

/** Story bosses are one-time in story mode but replayable in Free Mode. */
export function isStoryBoss(id: string): boolean {
  return BOSS_LIST.some((boss) => boss.id === id && boss.rank === 'major');
}
