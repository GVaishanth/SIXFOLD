export const FLOOR_LIST: FloorDef[] = Object.values(FLOOR_REGISTRY);

export const FLOOR_NAMES: string[] = FLOOR_LIST.map((f) => f.name);

export const TOTAL_FLOORS = FLOOR_LIST.length;
export const STORY_WAVES = 200;
export const WAVES_PER_FLOOR = 20;

export function getFloor(floorNumber: number): FloorDef {
  const clamped = Math.max(1, Math.min(TOTAL_FLOORS, Math.floor(floorNumber)));
  return FLOOR_REGISTRY[clamped] ?? FLOOR_REGISTRY[1];
}

/** Floor 1..10 for a story wave 1..200. */
export function floorForWave(wave: number): number {
  return Math.max(1, Math.min(TOTAL_FLOORS, Math.ceil(wave / WAVES_PER_FLOOR)));
}

/** Local wave inside the floor (1..20). */
export function waveInFloor(wave: number): number {
  return ((wave - 1) % WAVES_PER_FLOOR) + 1;
}

/** Training arena floor used by Free Mode. */
export const TRAINING_FLOOR: FloorDef = FLOOR_REGISTRY[4];
